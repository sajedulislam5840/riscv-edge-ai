"""Write firmware/build/model_data.h for the bare-metal firmware.

Packs the INT8 model (benchmarks/mnist/results/mnist_model.qbin), the calibrated integer
constants (web/js/quant_params.js, written by mnist_benchmark) and the ten example test images
(web/js/model_int8.js) into C arrays. It also computes the expected INT8 outputs for each image
with exact integer arithmetic (the same as the C++ engine), so the firmware can check itself.

For the custom MAC instructions it adds each layer's weights packed four bytes per 32-bit word,
neuron by neuron (W1_PACKED, W2_PACKED), and a per-neuron constant -Z_x * sum(w) (ZCORR1,
ZCORR2): the MAC multiplies raw signed bytes, and this term turns that into the layer's
sum((x - Z_x) * w).

Run from the repo root: python firmware/gen_model_header.py
"""
import base64
import os
import re
import struct

QBIN = "benchmarks/mnist/results/mnist_model.qbin"
PARAMS = "web/js/quant_params.js"
EXAMPLES = "web/js/model_int8.js"
OUT = "firmware/build/model_data.h"


def load_qbin(path):
    b = open(path, "rb").read()
    magic, n = struct.unpack_from("<II", b, 0)
    assert magic == 0x514E4554, "not a .qbin file"
    off, tensors = 8, []
    for _ in range(n):
        rows, cols, scale, zp = struct.unpack_from("<IIfi", b, off)
        off += 16
        data = list(struct.unpack_from(f"<{rows * cols}b", b, off))
        off += rows * cols
        tensors.append({"rows": rows, "cols": cols, "zp": zp, "data": data})
    return tensors


def load_params(path):
    js = open(path, encoding="utf-8").read()
    def block(name):
        m = re.search(name + r":\s*\{([^}]*)\}", js)
        return {k: float(v) for k, v in re.findall(r"(\w+):\s*(-?[0-9.eE+-]+)", m.group(1))}
    p = {k: block(k) for k in ("input", "hidden", "output", "layer1", "layer2")}
    for layer in ("layer1", "layer2"):
        p[layer] = {k: int(v) for k, v in p[layer].items()}
    for t in ("input", "hidden", "output"):
        p[t]["zeroPoint"] = int(p[t]["zeroPoint"])
    return p


def load_examples(path):
    js = open(path, encoding="utf-8").read()
    out = []
    for label, index, b64 in re.findall(r'\{ label: (\d+), index: (\d+), pixels: "([^"]+)" \}', js):
        out.append((int(label), int(index), list(base64.b64decode(b64))))
    return out


def requantize(x, m, s):  # identical to multiply_by_quantized_multiplier
    total = x * m
    return total << -s if s <= 0 else (total + (1 << (s - 1))) >> s


def dense(x, zx, W, b, l, zout, relu):
    K, N, w = W["rows"], W["cols"], W["data"]
    out = []
    for j in range(N):
        acc = sum((x[k] - zx) * (w[k * N + j] - W["zp"]) for k in range(K))
        acc += requantize(b["data"][j] - b["zp"], l["biasMultiplier"], l["biasShift"])
        r = requantize(acc, l["multiplier"], l["shift"]) + zout
        if relu and r < zout:
            r = zout
        out.append(max(-128, min(127, r)))
    return out


def packed_columns(W):
    """Weights [K][N] -> N rows of K/4 words; word c of neuron j holds w[4c..4c+3][j]."""
    K, N, w = W["rows"], W["cols"], W["data"]
    assert K % 4 == 0
    words = []
    for j in range(N):
        for c in range(K // 4):
            b = [w[(4 * c + i) * N + j] & 0xFF for i in range(4)]
            words.append(b[0] | b[1] << 8 | b[2] << 16 | b[3] << 24)
    return words


def zero_point_correction(W, zx):
    K, N, w = W["rows"], W["cols"], W["data"]
    return [-zx * sum(w[k * N + j] for k in range(K)) for j in range(N)]


def c_array(ctype, name, values, per_line=24):
    lines = [", ".join(str(v) for v in values[i:i + per_line]) for i in range(0, len(values), per_line)]
    return f"static const {ctype} {name}[{len(values)}] = {{\n  " + ",\n  ".join(lines) + "\n};\n"


W1, b1, W2, b2 = load_qbin(QBIN)
P = load_params(PARAMS)
examples = load_examples(EXAMPLES)
assert W1["zp"] == 0 and W2["zp"] == 0, "the firmware expects symmetric weights"

expected = []
for label, index, px in examples:
    x = [v - 128 for v in px]
    h = dense(x, P["input"]["zeroPoint"], W1, b1, P["layer1"], P["hidden"]["zeroPoint"], True)
    expected.append(dense(h, P["hidden"]["zeroPoint"], W2, b2, P["layer2"], P["output"]["zeroPoint"], False))

os.makedirs(os.path.dirname(OUT), exist_ok=True)
with open(OUT, "w", newline="\n") as f:
    f.write("// Generated by firmware/gen_model_header.py. Do not edit.\n#pragma once\n#include <stdint.h>\n\n")
    f.write(f"#define IN_SIZE {W1['rows']}\n#define HIDDEN_SIZE {W1['cols']}\n#define OUT_SIZE {W2['cols']}\n")
    f.write(f"#define NUM_EXAMPLES {len(examples)}\n\n")
    for name, t in (("input", "IN"), ("hidden", "HID"), ("output", "OUT")):
        f.write(f"#define ZP_{t} ({P[name]['zeroPoint']})\n")
    for i, layer in ((1, "layer1"), (2, "layer2")):
        l = P[layer]
        f.write(f"#define L{i}_MULT ({l['multiplier']})\n#define L{i}_SHIFT ({l['shift']})\n"
                f"#define L{i}_BIAS_MULT ({l['biasMultiplier']})\n#define L{i}_BIAS_SHIFT ({l['biasShift']})\n")
    f.write(f"#define B1_ZP ({b1['zp']})\n#define B2_ZP ({b2['zp']})\n\n")
    f.write(c_array("int8_t", "W1", W1["data"]))
    f.write(c_array("int8_t", "B1", b1["data"]))
    f.write(c_array("int8_t", "W2", W2["data"]))
    f.write(c_array("int8_t", "B2", b2["data"]))
    f.write(c_array("uint32_t", "W1_PACKED", packed_columns(W1), per_line=8))
    f.write(c_array("uint32_t", "W2_PACKED", packed_columns(W2), per_line=8))
    f.write(c_array("int32_t", "ZCORR1", zero_point_correction(W1, P["input"]["zeroPoint"]), per_line=12))
    f.write(c_array("int32_t", "ZCORR2", zero_point_correction(W2, P["hidden"]["zeroPoint"]), per_line=12))
    f.write(c_array("uint8_t", "LABELS", [e[0] for e in examples]))
    f.write(c_array("uint32_t", "TEST_INDEX", [e[1] for e in examples]))
    f.write(f"static const uint8_t IMAGES[{len(examples)}][784] = {{\n")
    for _, _, px in examples:
        f.write("  {" + ",".join(map(str, px)) + "},\n")
    f.write("};\n")
    f.write(f"static const int8_t EXPECTED[{len(examples)}][{W2['cols']}] = {{\n")
    for e in expected:
        f.write("  {" + ",".join(map(str, e)) + "},\n")
    f.write("};\n")
print(f"wrote {OUT}: {len(examples)} images, expected predictions",
      [max(range(10), key=lambda d: e[d]) for e in expected])
