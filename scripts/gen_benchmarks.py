"""Generate BENCHMARKS.md from web/js/results.js, so every number in it comes from a recorded run.

  python scripts/gen_benchmarks.py           write BENCHMARKS.md
  python scripts/gen_benchmarks.py --check   fail if BENCHMARKS.md differs from what results.js produces (used by CI)
"""
import json
import sys

RESULTS = "web/js/results.js"
OUT = "BENCHMARKS.md"


def load():
    js = open(RESULTS, encoding="utf-8").read()
    return json.loads(js.split("window.PROJECT_RESULTS = ", 1)[1].rsplit(";", 1)[0])


def n(x):
    return f"{x:,}"


def mhz(values):
    lo, hi = min(values), max(values)
    return f"{lo:.1f} to {hi:.1f} MHz"


def render(r):
    fw, soc, cs = r["firmware"], r["soc"], r["cosim"]
    sweep, area = r["socSweep"], r["socArea"]
    macs = fw["macsPerInference"]

    fair_instr = fw["optScalarInstructionsPerInference"] / fw["optMacInstructionsPerInference"]
    fair_cyc = soc["optScalarCycles"] / soc["optMacCycles"]
    plain_cyc = soc["scalarCycles"] / soc["optMacCycles"]

    e = area["ecp5"]
    f_no, f_mac = max(e["coreNoMac"]["fmaxMHz"]), max(e["coreMac"]["fmaxMHz"])
    t_no = soc["optScalarCycles"] / (f_no * 1e3)
    t_mac = soc["optMacCycles"] / (f_mac * 1e3)
    drop = (1 - f_mac / f_no) * 100

    L = []
    w = L.append
    w("# Benchmarks")
    w("")
    w("Generated by `scripts/gen_benchmarks.py` from `web/js/results.js`; CI fails if this file and the recorded results disagree. "
      "Every number below is a measurement of the code in this repository, and the section called *What is not measured* lists what is missing.")
    w("")
    w("## Summary")
    w("")
    w("| | Value | Measured on |")
    w("|---|---|---|")
    w(f"| Fair speed-up, instructions (unrolled scalar against unrolled MAC loop) | **{fair_instr:.2f}x** | Spike |")
    w(f"| Fair speed-up, clock cycles, memory with no wait states | **{fair_cyc:.2f}x** | PicoRV32 in RTL simulation |")
    w(f"| Fair speed-up, clock cycles, 16 wait states | **{sweep['rows'][-1]['speedup']:.2f}x** | PicoRV32 in RTL simulation |")
    w(f"| Estimated speed-up in time, from ECP5 clock speeds | **{t_no / t_mac:.1f}x** | cycles from RTL simulation, Fmax from nextpnr |")
    w(f"| Extra hardware for the MAC unit (ECP5) | {e['unit']['lut4']} LUT4, {e['unit']['ff']} flip-flops, {e['unit']['dsp']} DSP blocks | Yosys |")
    w(f"| Clock speed cost of the unit (ECP5, best seed) | {drop:.0f}% ({f_no:.1f} to {f_mac:.1f} MHz) | nextpnr |")
    w(f"| MNIST test accuracy, FP32 / INT8 | 98.23% / 98.21% | C++ engine, 10,000 images |")
    w("")
    w("## How each number is measured")
    w("")
    w("| Number | Tool | Command | Recorded in |")
    w("|---|---|---|---|")
    w("| Instructions per inference | Spike with the custom-instruction extension | `make -C firmware run` | `results.firmware` |")
    w("| Clock cycles per inference | PicoRV32 SoC compiled to C++ with Yosys CXXRTL; the firmware reads `rdcycle` | `bash hardware/scripts/soc_sim.sh mnist` | `results.soc` |")
    w("| Cycles with wait states | Same simulation; the testbench delays every memory reply | `bash hardware/scripts/soc_sweep.sh` | `results.socSweep` |")
    w("| LUTs, flip-flops, DSP blocks | `synth_ecp5` and `synth_ice40 -dsp` in Yosys | `bash hardware/scripts/soc_synth.sh` | `results.socArea` |")
    w("| Fmax | nextpnr-ecp5, LFE5U-25F CABGA256, three placement seeds | `bash hardware/scripts/soc_synth.sh` | `results.socArea` |")
    w("| Unit and wrapper correctness | RTL against 25,088 golden vectors | `bash hardware/scripts/cosim.sh` | `results.cosim` |")
    w("")
    w("CI re-runs the Spike, co-simulation and SoC simulation numbers on every push and compares them with the recorded file, "
      "and also checks that Spike and the RTL agree on every instruction count. "
      "The wait-state sweep and the area and Fmax numbers depend on tool builds and take longer, so they are recorded by hand and not re-checked in CI; "
      "the 0-wait-state row of the sweep is cross-checked against the SoC run.")
    w("")
    w("## Workload")
    w("")
    w(f"One inference of the 784-128-10 INT8 MLP on one MNIST image takes {n(macs)} multiply-accumulates. "
      f"The firmware runs ten test images (one per digit), {soc['imagesCorrect']} of {soc['imagesChecked']} are classified correctly, "
      "and every output byte matches the C++ engine for all five code versions. Each version runs the same network; only the inner loop differs.")
    w("")
    w("| Version | Inner loop |")
    w("|---|---|")
    w("| Scalar, plain | Byte loads and `mul`, one multiply-accumulate per step |")
    w("| Scalar, unrolled | The same, 16 multiply-accumulates per loop step |")
    w("| `simd_mac_clr` + `add` | One custom instruction per four multiply-accumulates, an `add` to carry the running total |")
    w("| `simd_macz` / `simd_macc` | The running total stays inside the unit |")
    w("| `simd_macz` / `simd_macc`, unrolled | The same, 8 custom instructions per loop step |")
    w("")
    w("The fair comparison is the two unrolled versions, because unrolling helps both and only the hardware differs between them.")
    w("")
    w("## Instructions per inference (Spike)")
    w("")
    w("Spike retires one instruction per step, so these are exact instruction counts and not clock cycles.")
    w("")
    w("| Version | Instructions | Per multiply-accumulate |")
    w("|---|---|---|")
    rows = [("Scalar, plain", "instructionsPerInference", 1), ("Scalar, unrolled", "optScalarInstructionsPerInference", 1),
            ("`simd_mac_clr` + `add`", "macClrAddInstructionsPerInference", 4), ("`simd_macz` / `simd_macc`", "macInstructionsPerInference", 4),
            ("`simd_macz` / `simd_macc`, unrolled", "optMacInstructionsPerInference", 4)]
    for name, key, per in rows:
        v = fw[key]
        unit = "" if per == 1 else " per 4"
        w(f"| {name} | {n(v)} | {v / macs * per:.1f}{unit} |")
    w("")
    w(f"Unrolled scalar against unrolled MAC: **{fair_instr:.2f}x** fewer instructions.")
    w("")
    w("## Clock cycles per inference (PicoRV32, no wait states)")
    w("")
    w("| Version | Instructions | Clock cycles | Cycles per instruction | Cycles vs plain scalar |")
    w("|---|---|---|---|---|")
    crow = [("Scalar, plain", "instructionsPerInference", "scalarCycles"), ("Scalar, unrolled", "optScalarInstructionsPerInference", "optScalarCycles"),
            ("`simd_mac_clr` + `add`", "macClrAddInstructionsPerInference", "macClrAddCycles"),
            ("`simd_macz` / `simd_macc`", "macInstructionsPerInference", "macCycles"),
            ("`simd_macz` / `simd_macc`, unrolled", "optMacInstructionsPerInference", "optMacCycles")]
    for name, ik, ck in crow:
        w(f"| {name} | {n(soc[ik])} | {n(soc[ck])} | {soc[ck] / soc[ik]:.1f} | {soc['scalarCycles'] / soc[ck]:.2f}x |")
    w("")
    w(f"Fair speed-up in cycles: **{fair_cyc:.2f}x**. Against the plain scalar loop the same hardware gives {plain_cyc:.2f}x, "
      "a figure that mixes the effect of the hardware with the effect of unrolling and is not used as the headline. "
      f"The same scalar code on the core without the unit takes {n(sweep['noMacScalarCycles'])} cycles, "
      f"{'exactly the same as with it' if sweep['noMacScalarCycles'] == soc['scalarCycles'] else 'which differs from the run with the unit'}.")
    w("")
    w("## Wait states")
    w("")
    w("Clock cycles per inference when every memory access takes extra cycles. Same binary, image 0.")
    w("")
    w("| Wait states | Scalar, unrolled | MAC, unrolled | Speed-up |")
    w("|---|---|---|---|")
    for row in sweep["rows"]:
        w(f"| {row['waitStates']} | {n(row['optScalar'])} | {n(row['optMac'])} | {row['speedup']:.2f}x |")
    w("")
    w("PicoRV32 has no cache and fetches every instruction from memory, so memory time grows with the instruction count and the speed-up stays nearly flat. "
      "A core with caches or tightly coupled memory would behave differently, and that is not measured here.")
    w("")
    w("## Area and clock speed")
    w("")
    w("| | LUT4 | Flip-flops | DSP blocks | Fmax |")
    w("|---|---|---|---|---|")
    for fam, label in (("ecp5", "ECP5"), ("ice40", "iCE40")):
        for key, name in (("coreNoMac", "Core without the unit"), ("coreMac", "Core with the unit"), ("unit", "MAC unit alone")):
            d = area[fam][key]
            fm = mhz(d["fmaxMHz"]) if "fmaxMHz" in d else ""
            w(f"| {name}, {label} | {n(d['lut4'])} | {d['ff']} | {d['dsp']} | {fm} |")
    w("")
    w("ECP5 numbers are after place-and-route (three seeds). iCE40 is synthesis only: the SoC has more pins than the UP5K package offers and the HX8K has no DSP blocks.")
    w("")
    w("### Wall-clock estimate")
    w("")
    w(f"One inference with the unrolled scalar loop: {n(soc['optScalarCycles'])} cycles at {f_no:.1f} MHz is **{t_no:.1f} ms**. "
      f"With the unit: {n(soc['optMacCycles'])} cycles at {f_mac:.1f} MHz is **{t_mac:.1f} ms**. "
      f"That is **{t_no / t_mac:.1f}x** faster, less than the {fair_cyc:.2f}x in cycles, because the unit lowers the clock speed by {drop:.0f}%. "
      "Both clock speeds are the best of three placement seeds; the estimate takes no memory system into account.")
    w("")
    w("## Correctness runs")
    w("")
    w(f"- Unit against golden vectors: {n(cs['unitVectors'])} vectors, {cs['unitMismatches']} mismatches.")
    w(f"- Custom-0 wrapper as an instruction stream: {n(cs['wrapperInstructions'])} instructions with {n(cs['wrapperIdleCycles'])} idle cycles mixed in, {cs['wrapperMismatches']} mismatches.")
    w(f"- Self-test of the custom instructions on the PicoRV32 SoC: {n(soc['isaChecks'])} checks, {'all pass' if soc['isaPass'] else 'FAILED'}.")
    w("- The same self-test on a core built without the unit stops on an illegal instruction; CI requires that, so the test is known to be able to fail.")
    w("")
    w("## Accuracy")
    w("")
    w("From `benchmarks/mnist/run_benchmark.cpp`, 10,000 MNIST test images, activation scales calibrated on 2,000 training images. "
      "These figures are not regenerated by this script; CI checks that the exported model file is reproduced bit for bit.")
    w("")
    w("| Configuration | Accuracy |")
    w("|---|---|")
    w("| FP32 reference | 98.23% |")
    w("| INT8 weights, FP32 activations | 98.23% |")
    w("| INT8 end to end, integer-only (main configuration) | 98.21% |")
    w("")
    w("## What is not measured")
    w("")
    w("- Memory is a flat array with a fixed number of wait states. No cache, no real DRAM or flash timing.")
    w("- PicoRV32 with its fast multiplier is the baseline. With the small serial multiplier the scalar code would be slower and the gain larger; that was not run.")
    w("- Xilinx 7-series timing and any ASIC flow were not run. iCE40 numbers for the full SoC are synthesis only.")
    w("- Clock speeds come from nextpnr on one device family, with three placement seeds; they are not silicon measurements.")
    w("- Both sides are compiled C at `-O2`. Hand-written assembly for either side was not tried.")
    w("- One network (784-128-10 MLP) on one dataset. Other layer shapes were not run.")
    w("- Power was not measured.")
    w("")
    w("## Reproduce")
    w("")
    w("```bash")
    w("bash firmware/setup_toolchain.sh && export PATH=\"$HOME/.riscv-edge-ai-tools/bin:$PATH\"")
    w("mkdir -p build")
    w("make -C firmware run | tee build/firmware_run.txt")
    w("bash hardware/scripts/cosim.sh | tee build/cosim.txt")
    w("bash hardware/scripts/soc_sim.sh isa   | tee build/soc_isa.txt")
    w("bash hardware/scripts/soc_sim.sh mnist | tee build/soc_mnist.txt")
    w("bash hardware/scripts/soc_sweep.sh | tee build/soc_sweep.txt")
    w("bash hardware/scripts/soc_synth.sh | tee build/soc_synth.txt")
    w("python3 scripts/record_results.py       # rewrite web/js/results.js")
    w("python3 scripts/gen_benchmarks.py       # rewrite this file")
    w("```")
    w("")
    return "\n".join(L)


def main():
    text = render(load())
    if "--check" in sys.argv:
        current = open(OUT, encoding="utf-8").read() if __import__("os").path.exists(OUT) else ""
        if current != text:
            print(f"{OUT} is out of date. Run scripts/gen_benchmarks.py and commit it.")
            sys.exit(1)
        print(f"{OUT} matches web/js/results.js")
        return
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote", OUT)


if __name__ == "__main__":
    main()
